/**
 * @file main.cpp
 * @brief 开发机工具。读一份手写指令列表，写出 C++ 字节数组。不扫描业务 cpp
 */

#include "ObfusProgram.h"
#include <fstream>
#include <iostream>
#include <sstream>
#include <string>
#include <vector>

namespace {

bool identifier(const std::string& name)
{
    if (name.empty()) {
        return false;
    }
    const char c0 = name[0];
    if (!((c0 >= 'A' && c0 <= 'Z') || (c0 >= 'a' && c0 <= 'z') || c0 == '_')) {
        return false;
    }
    for (std::size_t i = 1; i < name.size(); ++i) {
        const char c = name[i];
        if (!((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == '_')) {
            return false;
        }
    }
    return true;
}

std::string readAll(const std::string& path, std::string* error)
{
    std::ifstream in(path.c_str(), std::ios::binary);
    if (!in) {
        if (error) {
            *error = "cannot read the instruction list";
        }
        return std::string();
    }
    std::ostringstream ss;
    ss << in.rdbuf();
    return ss.str();
}

bool writeHeader(const std::string& path, const std::string& symbol, const std::vector<unsigned char>& bytes)
{
    std::ofstream out(path.c_str(), std::ios::binary);
    if (!out) {
        return false;
    }
    out << "/* Generated by Vision.ObfusTool. Load with ObfusProgram(bytes, size). */\n";
    out << "#ifndef VISION_OBFUS_" << symbol << "_H\n";
    out << "#define VISION_OBFUS_" << symbol << "_H\n\n";
    out << "static const unsigned char " << symbol << "[] = {\n";
    for (std::size_t i = 0; i < bytes.size(); ++i) {
        if (i % 12 == 0) {
            out << "    ";
        }
        out << "0x";
        const char* hex = "0123456789abcdef";
        out << hex[(bytes[i] >> 4) & 0xf] << hex[bytes[i] & 0xf];
        if (i + 1 != bytes.size()) {
            out << ",";
        }
        if (i % 12 == 11 || i + 1 == bytes.size()) {
            out << "\n";
        } else {
            out << " ";
        }
    }
    out << "};\n\n";
    out << "static const int " << symbol << "Size = " << bytes.size() << ";\n\n";
    out << "#endif\n";
    return static_cast<bool>(out);
}

}

int main(int argc, char** argv)
{
    if (argc < 3 || argc > 4) {
        std::cerr << "usage: Vision.ObfusTool <list.txt> <out.h> [symbol]\n";
        return 1;
    }
    const std::string symbol = argc == 4 ? argv[3] : "kObfusProgram";
    if (!identifier(symbol)) {
        std::cerr << "symbol is not a C identifier\n";
        return 1;
    }
    std::string error;
    const std::string text = readAll(argv[1], &error);
    if (!error.empty()) {
        std::cerr << error << "\n";
        return 1;
    }
    std::vector<unsigned char> bytes;
    if (!Vision::ObfusProgram::encode(text, &bytes, &error)) {
        std::cerr << (error.empty() ? "encode failed" : error) << "\n";
        return 1;
    }
    const Vision::ObfusProgram program(bytes.empty() ? 0 : &bytes[0], static_cast<int>(bytes.size()));
    if (!program.valid()) {
        std::cerr << "encoded bytes did not load\n";
        return 1;
    }
    if (!writeHeader(argv[2], symbol, bytes)) {
        std::cerr << "cannot write the header\n";
        return 1;
    }
    std::cout << symbol << " " << bytes.size() << " bytes\n";
    return 0;
}

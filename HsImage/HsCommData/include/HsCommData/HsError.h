#ifndef HSCOMMDATA_HSERROR_H
#define HSCOMMDATA_HSERROR_H

namespace HsCommData {

/**
 * @brief 错误码。无符号整数
 * 0 成功。1000 基础。2000 图像。3000 区域轮廓对象。
 * 4000 文件。5000 设备通信。10000 起算法工具，每个工具预留 100 个号。
 * 20000 起留给外部扩展。算法码写在 10000 段，中间空号不要占。
 * 下面的宏在文件作用域，不进本命名空间。
 */
typedef unsigned int HsError;

}

/**********************************************/
/* 0                                            */
/* 成功                                         */
/**********************************************/

#define HS_OK              0    /* 没有错误 */

/**********************************************/
/* 1000 - 1999                                  */
/* 基础错误。下标、类型、取值范围。             */
/* 调用方传错参数时抛，和具体图像内容无关。     */
/**********************************************/

#define HS_ERR_INDEX       1001 /* 下标越界。元组或对象 */
#define HS_ERR_TYPE        1002 /* 类型或种类不符 */
#define HS_ERR_INT_RANGE   1003 /* 整数超出 32 位 */
#define HS_ERR_NULL        1004 /* 调用方没有给出输出 */
#define HS_ERR_PARAM       1005 /* 工具参数缺失 */
#define HS_ERR_ACTION      1006 /* 动作未实现 */
#define HS_ERR_NO_ALG      1007 /* 算法未登记 */
#define HS_ERR_OPERATOR    1008 /* 算子失败。工具有自己的号时用工具号 */

/**********************************************/
/* 2000 - 2999                                  */
/* 图像与像素缓冲。行、尺寸、编码。             */
/**********************************************/

#define HS_ERR_IMAGE_ROW   2001 /* 图像行越界或没有像素 */
#define HS_ERR_IMAGE_EMPTY 2002 /* 没有图像或尺寸无效 */

/**********************************************/
/* 3000 - 3999                                  */
/* 区域、轮廓、对象。行程、句柄数据本身不合法。 */
/* 种类拿错仍用 HS_ERR_TYPE，不在本段。         */
/* 暂不定义具体号码。                           */
/**********************************************/

/**********************************************/
/* 4000 - 4999                                  */
/* 文件与序列化。读图、读写对象与元组。         */
/**********************************************/

#define HS_ERR_FILE_OPEN   4001 /* 打不开文件 */
#define HS_ERR_FILE_IO     4002 /* 读或写失败 */
#define HS_ERR_FILE_FORMAT 4003 /* 文件格式或版本不符 */

/**********************************************/
/* 5000 - 5999                                  */
/* 设备与通信。相机、光源、端口。               */
/* 不在本库定义。                               */
/**********************************************/

/**********************************************/
/* 10000 - 19999                                */
/* 算法错误。每个工具预留 100 个号。            */
/* 下一工具从 10700 起。                        */
/**********************************************/

/**********************************************/
/* 10000 - 10099                                */
/* 模板定位 locate.template                     */
/**********************************************/

#define HS_ERR_TMPL_NO_TEACH  10001 /* 没有示教区域 */
#define HS_ERR_TMPL_NO_MODEL  10002 /* 没有模板 */
#define HS_ERR_TMPL_NO_MATCH  10003 /* 没有匹配 */
#define HS_ERR_TMPL_OPERATOR  10004 /* 定位算子失败 */
#define HS_ERR_TMPL_NO_DIR    10005 /* 没有工具数据目录 */
#define HS_ERR_TMPL_METHOD    10006 /* 建模方式无法识别 */
#define HS_ERR_TMPL_CONTRAST  10007 /* 对比度无法识别 */
#define HS_ERR_TMPL_VALUE     10008 /* 数值或 auto 无法识别 */

/**********************************************/
/* 10100 - 10199                                */
/* 斑点 detect.blob                             */
/**********************************************/

#define HS_ERR_BLOB_NO_REGION 10101 /* 没有连通域 */
#define HS_ERR_BLOB_OPERATOR  10102 /* 斑点算子失败 */

/**********************************************/
/* 10200 - 10299                                */
/* 找线 locate.find_line                        */
/**********************************************/

#define HS_ERR_LINE_NONE      10201 /* 没有直线 */
#define HS_ERR_LINE_OPERATOR  10202 /* 找线算子失败 */

/**********************************************/
/* 10300 - 10399                                */
/* 图像拼接 preprocess.stitch                   */
/**********************************************/

#define HS_ERR_STITCH_FEW      10301 /* 图像不足两张 */
#define HS_ERR_STITCH_OPERATOR 10302 /* 拼接算子失败 */

/**********************************************/
/* 10400 - 10499                                */
/* 二维码 detect.qr                             */
/**********************************************/

#define HS_ERR_QR_NONE        10401 /* 没有二维码 */
#define HS_ERR_QR_OPERATOR    10402 /* 二维码算子失败 */

/**********************************************/
/* 10500 - 10599                                */
/* 一维码 detect.barcode                        */
/**********************************************/

#define HS_ERR_BAR_NONE       10501 /* 没有一维码 */
#define HS_ERR_BAR_OPERATOR   10502 /* 一维码算子失败 */

/**********************************************/
/* 10600 - 10699                                */
/* 采集 camera.acquire                          */
/**********************************************/

#define HS_ERR_ACQUIRE_NO_IMAGE 10601 /* 没有采集到图像 */
#define HS_ERR_ACQUIRE_CONVERT  10602 /* HsImage 转 HObject 失败 */

/**********************************************/
/* 20000 及以上                                 */
/* 外部扩展。现场或第三方模块。                 */
/* 不在本库定义。                               */
/**********************************************/

#endif
